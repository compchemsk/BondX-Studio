"""Browser end-to-end test (Playwright + Chromium): python3 tests/e2e.py
Walks every page with the demo and with 1US0+IDD594 (QM/MM), using the synthetic testing aids,
and fails on any page error or console error."""
import asyncio, os, sys, tempfile, json
from playwright.async_api import async_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = 'file://' + os.path.join(ROOT, 'dist', 'BondX_Studio.html')
SHOTS = os.path.join(ROOT, 'shots')
fails = []
def check(cond, msg):
    print(('PASS ' if cond else 'FAIL ') + msg)
    if not cond: fails.append(msg)
async def main():
    tmp = tempfile.mkdtemp(); os.makedirs(SHOTS, exist_ok=True)
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=os.environ.get('CHROME', '/usr/bin/google-chrome'), args=['--no-sandbox'])
        pg = await b.new_page(viewport={'width': 1500, 'height': 1000}, accept_downloads=True)
        errs = []
        pg.on('pageerror', lambda e: errs.append('pageerror: ' + str(e)))
        pg.on('console', lambda m: errs.append('console: ' + m.text) if m.type == 'error' and '3Dmol' not in m.text and 'net::' not in m.text and 'Failed to load resource' not in m.text else None)
        nav = lambda pid: pg.click(f'#side button[data-p={pid}]')
        async def shot(n):
            await pg.evaluate("document.querySelector('#toast').classList.remove('on'); document.querySelector('header.top').style.position='static'; document.querySelector('nav.side').style.position='static'; document.querySelector('nav.side').style.height='auto'; window.scrollTo(0,0)")
            await pg.screenshot(path=os.path.join(SHOTS, n + '.png'), full_page=True)
            await pg.evaluate("document.querySelector('header.top').style.position=''; document.querySelector('nav.side').style.position=''; document.querySelector('nav.side').style.height=''")
        async def dl(sel, name):
            async with pg.expect_download() as d: await pg.click(sel)
            f = os.path.join(tmp, name); await (await d.value).save_as(f); return f
        await pg.goto(URL); await pg.wait_for_timeout(1500)
        check(await pg.locator('#side button').count() == 12, 'sidebar has 12 entries')
        await pg.click('#btnTutorial'); await pg.wait_for_timeout(200)
        check(await pg.locator('#tutNav button').count() == 5, 'tutorial has five pages')
        for i in range(4): await pg.click('#tutNext')
        check('cannot' in (await pg.inner_text('#tutBody')), 'tutorial page 5 shows scope')
        await pg.click('#tutNext'); await pg.wait_for_timeout(200)
        check(await pg.locator('#pg-structure.on').count() == 1, 'tutorial ends on Load structure')
        foot = await pg.inner_text('footer'); check('Soumyajit Karmakar' in foot and 'Have a Good Day' in foot and 'soumyajitkarmakar.iit@gmail.com' in foot and ' v2' not in foot, 'footer branding kept')
        await pg.click('#btnDemo'); await pg.wait_for_timeout(400)
        check('Loaded' in await pg.inner_text('#loadMsg'), 'demo loads')
        check(await pg.locator('#pg-structure .assume li').count() >= 3, 'structure assumptions shown')
        await shot('01_structure')
        # detection with a changed parameter
        await nav('detect')
        await pg.fill('#pg-detect input[data-p="geom.theta1Min"]', '145'); await pg.dispatch_event('#pg-detect input[data-p="geom.theta1Min"]', 'change')
        check(await pg.locator('#pg-detect .prow.changed').count() >= 1, 'changed parameter highlighted')
        asum = await pg.inner_text('#pg-detect .assume'); check('145' in asum, 'assumptions update live with parameter (145°)')
        await pg.click('#pg-detect .prow.changed button[data-reset]'); await pg.wait_for_timeout(100)
        check(await pg.locator('#pg-detect .prow.changed').count() == 0, 'per-field reset works')
        await pg.click('#btnDetect'); await pg.wait_for_timeout(300)
        n = await pg.locator('#dTable tbody tr').count(); check(n >= 2, f'demo detection rows = {n}')
        await pg.click('#btnToReg'); await shot('02_detect')
        await nav('traj'); await pg.click('#btnTDemo'); await pg.click('#btnTraj'); await pg.wait_for_timeout(1500)
        n = await pg.locator('#tTable tbody tr').count(); check(n >= 1, f'trajectory persistent XB rows = {n}')
        await pg.click('#btnTReg'); await shot('03_traj')
        # QM cluster
        await nav('qm'); await pg.wait_for_timeout(200)
        boxes = await pg.query_selector_all('#qmReg .selc')
        for bx in boxes:
            v = await bx.get_attribute('value')
            if v in ('XB-001', 'XB-002'): await bx.check()
            else: await bx.uncheck()
        await pg.wait_for_timeout(200)
        await pg.click('#btnBuild'); await pg.wait_for_timeout(300)
        check(await pg.is_visible('#qOut'), 'QM cluster model built')
        tabs = await pg.locator('#qTabs button').all_inner_texts(); check(any(t.endswith('_nbo.com') for t in tabs), 'Gaussian input written: ' + ','.join(tabs))
        check(await pg.locator('#qCharges tbody tr').count() >= 2, 'fragment charge table shown')
        await shot('04_qm_cluster')
        # NBO
        await nav('nbo'); await pg.click('details:has(#btnFakeNbo) > summary')
        f = await dl('#btnFakeNbo', 'nbo.log'); await pg.set_input_files('#dropNbo input', f); await pg.wait_for_timeout(300)
        res = await pg.inner_text('#nRes'); check('VERIFIED' in res, 'NBO gate verifies synthetic output')
        await shot('05_nbo')
        # EDA
        await nav('eda'); f = await dl('#btnEdaIn', 'eda.in')
        check('$rem' in open(f).read() and 'EDA2' in open(f).read(), 'EDA input contains $rem / EDA2')
        await pg.click('details:has(#btnFakeEda) > summary'); f = await dl('#btnFakeEda', 'eda.out'); await pg.set_input_files('#dropEda input', f); await pg.wait_for_timeout(300)
        check(await pg.locator('#eTable tbody tr').count() >= 1, 'EDA table filled'); await shot('06_eda')
        await nav('quality'); await pg.wait_for_timeout(300)
        rows = await pg.locator('#qTable tbody tr').count(); check(rows >= 3, f'scorecard rows = {rows}')
        rep = await dl('#btnRep', 'report.html'); rtxt = open(rep).read()
        check('CONFIDENTIAL' not in rtxt and 'Assumptions' in rtxt and 'Changed parameters' in rtxt, 'report has no confidential banner; has assumptions, changed parameters')
        rr = json.load(open(await dl('#btnRunJson', 'run.json'))); check('assumptions' in rr and 'T3' in rr['assumptions'], 'run record contains assumptions')
        await shot('07_quality')
        # parameters page
        await nav('params'); await pg.wait_for_timeout(200)
        total = await pg.locator('#pList .prow').count(); check(total >= 80, f'all parameters listed ({total})')
        await pg.fill('#pSearch', 'boundary'); await pg.dispatch_event('#pSearch', 'input')
        check(await pg.locator('#pList .prow').count() >= 1, 'parameter search works')
        await pg.fill('#pSearch', ''); await pg.dispatch_event('#pSearch', 'input')
        pf = await dl('#pExport', 'params.json'); check(json.load(open(pf))['kind'] == 'BondX-parameters', 'parameter export')
        await shot('08_params')
        await nav('method'); await shot('09_method')
        await nav('guide'); await shot('11_tutorial')
        sf = await dl('#btnSaveSession', 'session.json')
        # second run: 1US0 with QM/MM
        await pg.reload(); await pg.wait_for_timeout(800)
        await pg.set_input_files('#dropPdb input', os.path.join(ROOT, 'tests/ref/1US0_IDD594.pdb')); await pg.wait_for_timeout(800)
        await nav('detect'); await pg.click('#btnDetect'); await pg.wait_for_timeout(500)
        txt = await pg.inner_text('#dTable'); check('THR' in txt and 'OG1' in txt, '1US0: Br···OG1 Thr113 found')
        await pg.click('#btnToReg')
        await nav('qm'); await pg.click('#qEnvSeg button[data-env=qmmm]'); await pg.wait_for_timeout(200)
        for bx in await pg.query_selector_all('#qmReg .selc'): await bx.check()
        await pg.wait_for_timeout(600)
        check(await pg.locator('#protTable select[data-prot]').count() >= 1, 'protonation table with choices')
        await pg.select_option('#pg-qm select[data-p="mm.boundary"]', 'Z1'); await pg.wait_for_timeout(100)
        await pg.select_option('#pg-qm select[data-p="qm.program"]', 'orca'); await pg.wait_for_timeout(100)
        check(await pg.input_value('#pg-qm input[data-p="qm.method"]') == 'wB97X-D3', 'program change resets method default')
        check('licensed program' in await pg.inner_text('#qProgNote'), 'ORCA NBO 7 caution shown under program')
        await pg.click('#btnBuild'); await pg.wait_for_timeout(1500)
        check('NBO 7' in await pg.inner_text('#qWarn'), 'ORCA NBO 7 caution in model warnings')
        inp = await pg.evaluate("() => { const b = [...document.querySelectorAll('#qTabs button')].find(x => x.textContent.endsWith('_nbo.inp')); b.click(); return document.querySelector('#qCode').textContent; }")
        check('CAUTION: ORCA has no built-in NBO' in inp and inp.split('\n')[6].startswith('!'), 'ORCA input carries the caution comments')
        await pg.select_option('#pg-qm select[data-p="qm.program"]', 'gaussian'); await pg.wait_for_timeout(150)
        check((await pg.inner_text('#qProgNote')).strip() == '', 'caution hidden for Gaussian pop=nbo')
        await pg.select_option('#pg-qm select[data-p="qm.program"]', 'orca'); await pg.wait_for_timeout(150)
        k = await pg.inner_text('#qEmb'); check('Z1' in k, 'QM/MM embedding summary shows Z1')
        tabs = await pg.locator('#qTabs button').all_inner_texts(); check(any(t.endswith('.pc') for t in tabs) and any(t.endswith('_mm_charges.csv') for t in tabs), 'ORCA .pc + charges CSV written')
        net = await pg.locator('#qEmb .kpi').nth(1).inner_text(); print('   net MM charge kpi:', net.replace('\n', ' '))
        await shot('10_qmmm_1US0')
        # session reload
        await pg.reload(); await pg.wait_for_timeout(800); await pg.set_input_files('#inSession', sf); await pg.wait_for_timeout(800)
        await nav('quality'); check(await pg.locator('#qTable tbody tr').count() == rows, 'session restored candidates')
        await b.close()
    for e in errs: print('ERR', e)
    check(not errs, 'no page/console errors')
    print(f'\n{len(fails)} failure(s)'); sys.exit(1 if fails else 0)
asyncio.run(main())
